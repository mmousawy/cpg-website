import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderToStaticMarkup } from 'react-dom/server';

import { routes } from '../src/config/routes';
import { helpSections } from '../src/content/help';
import { licensesHelpSections } from '../src/content/help/licenses';
import type { FAQSection } from '../src/content/help/types';
import { stripHtml } from '../src/utils/stripHtml';

type HelpSearchEntry = {
  itemId: string;
  title: string;
  sectionTitle: string;
  searchText: string;
  url: string;
};

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '../src/lib/help/helpSearchIndex.generated.ts');

function flattenSections(sections: FAQSection[], baseUrl: string): HelpSearchEntry[] {
  return sections.flatMap((section) =>
    section.items.map((item) => {
      const body = stripHtml(renderToStaticMarkup(item.content));
      const searchText = [section.title, item.title, body].join(' ').toLowerCase();

      return {
        itemId: item.id,
        title: item.title,
        sectionTitle: section.title,
        searchText,
        url: `${baseUrl}#${item.id}`,
      };
    }),
  );
}

export function buildHelpSearchEntries(): HelpSearchEntry[] {
  return [
    ...flattenSections(helpSections, routes.help.url),
    ...flattenSections(licensesHelpSections, routes.helpLicenses.url),
  ];
}

export function generateHelpSearchIndex(): number {
  const entries = buildHelpSearchEntries();

  const file = `/* eslint-disable */
// Generated by scripts/generate-help-search-index.ts — do not edit by hand.
// Updated automatically on commit when src/content/help changes; CI verifies via verify-help-search-index.test.ts.

import type { HelpSearchEntry } from './helpSearchIndex';

export const helpSearchEntries: HelpSearchEntry[] = ${JSON.stringify(entries, null, 2)};
`;

  writeFileSync(outPath, file, 'utf8');
  console.log(`Wrote ${entries.length} help search entries to ${outPath}`);
  return entries.length;
}
