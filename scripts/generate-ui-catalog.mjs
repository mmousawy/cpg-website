import fs from 'node:fs';
import path from 'node:path';

const root = path.join(process.cwd(), 'src/components');

/** Components with live story frames in registry (basename without .tsx). */
const LIVE_SHARED = new Set([
  'AutocompleteInput',
  'ArrowLink',
  'AnimatedPopoverPanel',
  'AuthorRow',
  'BottomSheet',
  'Button',
  'CardBadges',
  'CardLikes',
  'Checkbox',
  'ClickableAvatar',
  'ContentHeader',
  'DetailSidebar',
  'DropZone',
  'EmptyState',
  'ErrorMessage',
  'GridCheckbox',
  'HelpAccordion',
  'HelpLink',
  'Input',
  'InterestCloud',
  'InterestInput',
  'JavaScriptRequired',
  'LoadingSpinner',
  'MemberCard',
  'PageLoading',
  'Popover',
  'ProfileStatsBadges',
  'RichDescriptionView',
  'SectionMobileNav',
  'SectionSidebar',
  'Select',
  'SignUpCTA',
  'StackedAvatarsPopover',
  'StickyActionBar',
  'SuccessMessage',
  'Tag',
  'TagCloud',
  'TagCloudSkeleton',
  'TagInput',
  'TagShape',
  'Textarea',
  'Toggle',
  'Tooltip',
  'ViewCount',
]);

const CATALOG_REASONS = {
  shared: (name) => {
    if (LIVE_SHARED.has(name)) return null;
    if (name.startsWith('_')) return 'Internal dev probe';
    return 'Needs data, providers, or mutations';
  },
  icons: () => null,
  default: () => 'Feature component; needs app data or context',
};

function walk(dir, acc = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      walk(full, acc);
    } else if (ent.name.endsWith('.tsx')) {
      acc.push(full);
    }
  }
  return acc;
}

const files = walk(root).sort();

const byGroup = new Map();

for (const file of files) {
  const rel = path.relative(path.join(process.cwd(), 'src/components'), file).replace(/\\/g, '/');
  const parts = rel.split('/');
  const group = parts.length === 1 ? 'root' : parts[0];
  const basename = path.basename(file, '.tsx');
  const reasonFn = CATALOG_REASONS[group] ?? CATALOG_REASONS.default;
  const reason = reasonFn(basename);
  const isLive = reason === null;
  if (!byGroup.has(group)) byGroup.set(group, []);
  byGroup.get(group).push({
    name: basename,
    path: `src/components/${rel}`,
    catalogOnly: !isLive,
    ...(reason ? { catalogReason: reason } : {}),
  });
}

const groupOrder = [...byGroup.keys()].sort((a, b) => a.localeCompare(b));

const output = `/* eslint-disable -- generated by scripts/generate-ui-catalog.mjs */
export type UiCatalogEntry = {
  name: string;
  path: string;
  catalogOnly: boolean;
  catalogReason?: string;
};

export type UiComponentGroup = {
  id: string;
  label: string;
  entries: UiCatalogEntry[];
};

export const uiComponentGroups: UiComponentGroup[] = ${JSON.stringify(
    groupOrder.map((id) => ({
      id,
      label: id === 'root' ? 'Root' : id.charAt(0).toUpperCase() + id.slice(1),
      entries: byGroup.get(id),
    })),
    null,
    2,
  )};
`;

const outPath = path.join(process.cwd(), 'src/dev/ui/componentCatalog.ts');
fs.writeFileSync(outPath, output);
console.log(`Wrote ${outPath} (${files.length} components, ${groupOrder.length} groups)`);
